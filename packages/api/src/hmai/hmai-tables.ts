/**
 * Parse directory name format: D240101_T120000_001
 * Returns Date object or null if invalid
 */
export function parseDirName(dirName: string): Date | null {
  const parts = dirName.split('_');
  if (
    parts.length >= 3 &&
    parts[0].startsWith('D') &&
    parts[0].length === 7 &&
    parts[1].startsWith('T') &&
    parts[1].length === 7
  ) {
    const dateStr = parts[0].slice(1); // Remove 'D'
    const timeStr = parts[1].slice(1); // Remove 'T'
    const year = `20${dateStr.slice(0, 2)}`;
    const month = dateStr.slice(2, 4);
    const day = dateStr.slice(4, 6);
    const hour = timeStr.slice(0, 2);
    const minute = timeStr.slice(2, 4);
    const second = timeStr.slice(4, 6);
    return new Date(`${year}-${month}-${day}T${hour}:${minute}:${second}`);
  }
  return null;
}

/**
 * Extract metric name from CSV filename
 * Example: SUBSYSTEM_clpr.csv -> clpr
 */
export function getMetricFromFileName(fileName: string): HMAIMetric | null {
  const metric = fileName.split('_').pop()?.split('.')[0].toLowerCase();
  if (metric && HMAI_METRICS.includes(metric as HMAIMetric)) {
    return metric as HMAIMetric;
  }
  return null;
}


